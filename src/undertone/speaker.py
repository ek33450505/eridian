"""The single, security-critical choke point for ALL text reaching a TTS engine.

Everything undertone speaks goes through prepare_speech, via one of two exits:
build_say_argv (the `say` argv; used by player.SpeechQueue and
player.RenderedSpeechQueue) and espeak_phonemes (Kokoro's G2P step, which runs
espeak-ng as a separate program so its GPL-3.0 code stays out of our process,
the way `say` does).
The commands come from UNDERTONE_SAY_CMD (default "say") and
UNDERTONE_ESPEAK_CMD (default "espeak-ng"); tests MUST override both to stubs
that never produce real audio.
"""

from __future__ import annotations

import os
import re
import subprocess
import unicodedata

from .spoken import sanitize_for_tts

# Seconds before a hung espeak-ng is abandoned; the caller skips the sentence.
ESPEAK_TIMEOUT_S = 5.0

# Upper bound on one utterance. SentenceChunker chunks are ~240 chars or fewer,
# so this is generous; it stops a huge reply from holding the render worker for
# the whole espeak timeout.
MAX_SPEECH_CHARS = 1000

# espeak-ng -q --ipa drops punctuation, which Kokoro needs. A punctuation run
# followed by whitespace/end is a clause boundary; "3.5" and the inner "." of
# "e.g." are not (no whitespace after them).
_CLAUSE_END = re.compile(r"[,;:.!?…—]+(?=\s|$)")

# Lone surrogates survive json.loads of model replies but cannot be UTF-8
# encoded: Popen / subprocess.run raise UnicodeEncodeError, which the speech
# workers (catching only OSError) would not survive.
_SURROGATE_RE = re.compile("[\ud800-\udfff]")


def prepare_speech(text: str) -> str | None:
    """NUL-strip and sanitize_for_tts text; return None if nothing speakable remains.

    The ONE place the scrub happens; every TTS exit calls it first.
    """
    # subprocess.Popen raises ValueError on an embedded NUL byte -- strip it
    # rather than letting one malformed reply break the speech worker.
    text = text.replace("\x00", "")
    # Strip BEFORE sanitize_for_tts so a surrogate cannot split "jar<s>vis"
    # past the wake-word scrub.
    text = _SURROGATE_RE.sub("", text)
    # NFKC before the scrub: fullwidth [[ ]] would survive the ASCII-only
    # bracket strip (whether `say` honours them is unverified), and fullwidth
    # "jarvis" only becomes "jarvis" -- and so matchable -- after folding.
    text = unicodedata.normalize("NFKC", text)
    # Hard control, not model compliance: the wake detector stays live while
    # we speak, so TTS saying the wake phrase could self-trigger it (cut off
    # speech, or capture the tail as a command and confirm its own action).
    # sanitize_for_tts also strips every [ and ], which neutralizes the
    # [[inpt PHON ...]] commands honored by both `say` and espeak-ng.
    text = sanitize_for_tts(text)
    if not text.strip():
        return None
    if len(text) > MAX_SPEECH_CHARS:
        # Cut AFTER the scrub so a cut cannot split the wake word before it is
        # replaced. Prefer a word boundary; hard-cut when there is none.
        ws = [i for i in (text.rfind(c, 0, MAX_SPEECH_CHARS + 1) for c in "\n\t ") if i > 0]
        cut = max(ws) if ws else MAX_SPEECH_CHARS
        text = text[:cut]
        if not text.strip():
            return None
    return text


def build_say_argv(text: str, *, out_path: str | None = None) -> list[str] | None:
    """prepare_speech text; return None if empty; else [say_cmd, (-v voice), "--", text].

    With out_path, `say` renders to a 16 kHz mono int16 WAV file instead of
    speaking: [say_cmd, (-v voice), -o, out_path, --file-format=WAVE,
    --data-format=LEI16@16000, "--", text]. out_path is always generated by
    undertone (a private temp file), never derived from model text.
    """
    text = prepare_speech(text)
    if text is None:
        return None
    say_cmd = os.environ.get("UNDERTONE_SAY_CMD", "say")
    voice = os.environ.get("UNDERTONE_VOICE", "Evan (Enhanced)")
    cmd = [say_cmd]
    if voice:
        cmd += ["-v", voice]
    if out_path is not None:
        # Every flag goes before "--"; out_path is ours, not model text.
        cmd += ["-o", out_path, "--file-format=WAVE", "--data-format=LEI16@16000"]
    # "--" stops `say` (and any well-behaved stub) from parsing `text` as
    # flags -- without it, a reply containing e.g. "-o/path/to/overwrite"
    # is argv flag injection into the TTS command. This is the ONE place
    # that builds the say argv; player.py's SpeechQueue uses it, and cli.py
    # never shells out itself.
    cmd += ["--", text]
    return cmd


def espeak_phonemes(text: str) -> str | None:
    """IPA phonemes for text via espeak-ng, with punctuation marks restored.

    Kokoro's ONLY text entry. Returns None when nothing is speakable or
    espeak-ng fails (missing, nonzero exit, timeout); the caller skips the
    sentence.
    """
    # Sanitize FIRST: espeak-ng honors [[...]] phoneme input, so unscrubbed
    # text could smuggle the wake word in as phonemes with no letters.
    text = prepare_speech(text)
    if text is None:
        return None
    # Newline is our line protocol with espeak (one output line per segment),
    # so no newline may survive inside a segment.
    text = " ".join(text.split())

    segments: list[str] = []
    marks: list[str] = []
    pos = 0
    for m in _CLAUSE_END.finditer(text):
        seg = text[pos:m.start()].strip()
        pos = m.end()
        if seg:
            segments.append(seg)
            marks.append(m.group()[-1])
    tail = text[pos:].strip()
    if tail:
        segments.append(tail)
        marks.append("")
    if not segments:
        return None

    # Text goes on stdin, never argv, so it can never be parsed as a flag.
    argv = [os.environ.get("UNDERTONE_ESPEAK_CMD", "espeak-ng"), "-q", "--ipa", "-v", "en-us"]
    try:
        proc = subprocess.run(
            argv,
            input="\n".join(segments),
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",  # neither encode nor decode may raise in the worker
            timeout=ESPEAK_TIMEOUT_S,
        )
    except (OSError, subprocess.TimeoutExpired):
        return None
    if proc.returncode != 0:
        return None

    lines = [ln.strip() for ln in proc.stdout.splitlines()]
    lines = [ln for ln in lines if ln]
    if len(lines) == len(segments):
        result = " ".join(line + mark for line, mark in zip(lines, marks))
    else:
        # espeak split a segment itself; positions no longer line up, so keep
        # the phonemes and only the final mark.
        result = " ".join(lines) + marks[-1]
    return result or None
